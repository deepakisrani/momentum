import { execFileSync, spawn } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const cli = process.platform === 'win32'
  ? resolve(root, 'node_modules', '.bin', 'supabase.cmd')
  : resolve(root, 'node_modules', '.bin', 'supabase')

function runSupabase(args, capture = false) {
  return execFileSync(cli, args, capture
    ? { cwd: root, encoding: 'utf8', shell: process.platform === 'win32', stdio: ['ignore', 'pipe', 'inherit'] }
    : { cwd: root, shell: process.platform === 'win32', stdio: 'inherit' })
}

try {
  runSupabase(['start'])
  const status = JSON.parse(runSupabase(['status', '--output', 'json'], true))
  const apiUrl = status.API_URL ?? status.api_url
  const publishableKey = status.PUBLISHABLE_KEY ?? status.publishable_key
  if (!apiUrl || !publishableKey) throw new Error('Supabase status did not return an API URL and publishable key.')
  writeFileSync(resolve(root, '.env.development.local'), [
    '# Generated by `npm run dev:local`; do not commit.',
    `VITE_SUPABASE_URL=${apiUrl}`,
    `VITE_SUPABASE_PUBLISHABLE_KEY=${publishableKey}`,
    'VITE_LOCAL_SUPABASE=true',
    '',
  ].join('\n'))
  const vite = spawn(process.execPath, [resolve(root, 'node_modules', 'vite', 'bin', 'vite.js')], {
    cwd: root,
    stdio: 'inherit',
  })
  vite.on('exit', (code) => process.exit(code ?? 0))
} catch (error) {
  console.error(`Could not start local Momentum: ${error instanceof Error ? error.message : String(error)}`)
  process.exit(1)
}
